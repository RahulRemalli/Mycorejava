package com.languagefundamentals_Loops;

// write a program to print 1 to 10 and 10 to 1 numbers using for loop.
public class Lp1 {

	public static void main(String[] args) {
		for (int i = 1; i <= 10; i++) {
			System.out.print(i + " ");
		}
	
		for (int i = 10; i >= 1; i--) {
			
			System.out.print(i + " ");
		}
	
	}
	

}
