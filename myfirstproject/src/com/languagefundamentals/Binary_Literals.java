package com.languagefundamentals;

public class Binary_Literals {
	public static void main(String[] args) {
		int a1 = 123;
		int a2 = 0b1101;  // 128 64 32 16 8 4 2 1 
		                  //              1  1  0  1
		int a3 = 0b0011;
		
		
		System.out.println(a1);
		System.out.println(a2);
		System.out.println(a3);
	}

}
